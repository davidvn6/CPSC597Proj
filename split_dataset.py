"""
split_dataset.py

Exclude identical-file duplicate copies from the inventory and
create training, validation, and testing assignments.

Run from the CPSC597Proj folder:
    python .\\split_dataset.py

Input:
    results/audit/image_inventory.csv

Outputs:
    results/splits/train.csv
    results/splits/val.csv
    results/splits/test.csv
    results/splits/removed_duplicates.csv
    results/splits/split_distribution.csv
    results/splits/split_summary.txt

Original images are not moved, changed, or deleted.
"""

import random
from pathlib import Path

import pandas as pd


# Find the project folder containing this Python file.
ROOT = Path(__file__).resolve().parent

# Locate the inventory generated by the audit script.
INVENTORY = ROOT / "results" / "audit" / "image_inventory.csv"

# Set the output folder for the new dataset assignments.
OUT = ROOT / "results" / "splits"

# Use a fixed seed to make the assignments reproducible.
SEED = 42

# Set the desired proportions for each dataset split.
# Actual proportions may differ slightly because groups stay together.
RATIOS = {
    "train": 0.70,
    "val": 0.15,
    "test": 0.15,
}

# Define the two classification labels.
CLASSES = ["NORMAL", "PNEUMONIA"]


def main():
    # ---------------------------------------------------------------
    # 1. Load and validate the image inventory.
    # ---------------------------------------------------------------

    if not INVENTORY.is_file():
        raise SystemExit(f"Inventory not found: {INVENTORY}")

    # Read hashes and candidate patient IDs as strings.
    df = pd.read_csv(
        INVENTORY,
        dtype={"patient": "string", "md5": "string"},
    )

    # Confirm that the inventory contains the required columns.
    required = {"path", "label", "patient", "md5", "split"}

    if not required.issubset(df.columns):
        raise SystemExit("The inventory is missing required columns.")

    if df.empty:
        raise SystemExit("The inventory contains no images.")

    if df["md5"].isna().any():
        raise SystemExit("Some images have no hash. Rerun the audit.")

    if not df["label"].isin(CLASSES).all():
        raise SystemExit("Unexpected class labels found.")

    if df["path"].isna().any():
        raise SystemExit("Some images have no recorded path.")

    if df["path"].duplicated().any():
        raise SystemExit("The inventory contains repeated paths.")

    # Confirm that every recorded image still exists.
    for path in df["path"]:
        if not (ROOT / path).is_file():
            raise SystemExit(f"Image not found: {ROOT / path}")

    # Sort paths so the same duplicate copy is retained on every run.
    df = df.sort_values("path").reset_index(drop=True)

    # Stop if identical files have contradictory class labels.
    label_counts = df.groupby("md5")["label"].nunique()

    if (label_counts > 1).any():
        raise SystemExit(
            "Identical files have conflicting labels. Review them first."
        )

    # ---------------------------------------------------------------
    # 2. Build groups of related images.
    # ---------------------------------------------------------------

    # Each image initially belongs to its own group.
    parents = list(range(len(df)))

    def find(index):
        """Find the representative of an image's connected group."""
        while parents[index] != index:
            parents[index] = parents[parents[index]]
            index = parents[index]

        return index

    def join(first, second):
        """Combine the groups containing two related images."""
        first_root = find(first)
        second_root = find(second)

        if first_root != second_root:
            parents[second_root] = first_root

    # Track the first image associated with each candidate ID and hash.
    seen_patients = {}
    seen_hashes = {}

    for index, row in df.iterrows():
        candidate = row["patient"]

        # Keep matching filename-derived candidate IDs together.
        # These IDs are not verified patient identities.
        if pd.notna(candidate):
            if candidate in seen_patients:
                join(index, seen_patients[candidate])
            else:
                seen_patients[candidate] = index

        file_hash = row["md5"]

        # Join identical files even when their candidate IDs differ.
        if file_hash in seen_hashes:
            join(index, seen_hashes[file_hash])
        else:
            seen_hashes[file_hash] = index

    # Record the final connected group for each image.
    df["group_id"] = [
        find(index) for index in range(len(df))
    ]

    # ---------------------------------------------------------------
    # 3. Select one copy of each identical file.
    # ---------------------------------------------------------------

    # Keep the first image for each hash and record excluded copies.
    duplicate_mask = df.duplicated("md5", keep="first")
    removed = df[duplicate_mask].copy()
    split_data = df[~duplicate_mask].copy()

    # Preserve the original split names for traceability.
    split_data = split_data.rename(
        columns={"split": "original_split"}
    )

    # Create a column for the new split assignments.
    split_data["split"] = ""

    # The allocation method below handles one class at a time.
    # Stop if a connected group contains both classification labels.
    group_labels = (
        split_data.groupby("group_id")["label"].nunique()
    )

    if (group_labels > 1).any():
        raise SystemExit(
            "A connected group contains multiple classes. "
            "Review its candidate IDs before splitting."
        )

    # ---------------------------------------------------------------
    # 4. Assign whole groups to training, validation, and testing.
    # ---------------------------------------------------------------

    rng = random.Random(SEED)

    for label in CLASSES:
        class_rows = split_data[split_data["label"] == label]

        if class_rows.empty:
            raise SystemExit(f"No images found for {label}.")

        # Collect the connected groups belonging to this class.
        groups = list(class_rows.groupby("group_id"))

        if len(groups) < 3:
            raise SystemExit(f"Too few groups to split {label}.")

        # Randomize group order using the fixed seed.
        rng.shuffle(groups)

        # Calculate target image counts and track assigned counts.
        targets = {}
        counts = {}

        for split, ratio in RATIOS.items():
            targets[split] = len(class_rows) * ratio
            counts[split] = 0

        for group_id, group in groups:
            # Select the split with the lowest fraction of its target filled.
            selected = None
            lowest_fraction = float("inf")

            for split in RATIOS:
                fraction = counts[split] / targets[split]

                if fraction < lowest_fraction:
                    lowest_fraction = fraction
                    selected = split

            # Assign every image in this group to the same split.
            split_data.loc[group.index, "split"] = selected
            counts[selected] += len(group)

    # ---------------------------------------------------------------
    # 5. Verify the new assignments.
    # ---------------------------------------------------------------

    # Every connected group must belong to exactly one split.
    group_split_counts = (
        split_data.groupby("group_id")["split"].nunique()
    )

    if (group_split_counts > 1).any():
        raise RuntimeError("A group crosses dataset splits.")

    # Each retained file hash must be unique.
    if split_data["md5"].duplicated().any():
        raise RuntimeError("Identical-file duplicates remain.")

    # Every image must have a valid split assignment.
    if not split_data["split"].isin(RATIOS).all():
        raise RuntimeError("Some images have no valid split.")

    # Add numeric labels for the future training script.
    split_data["target"] = split_data["label"].map({
        "NORMAL": 0,
        "PNEUMONIA": 1,
    })

    # Count retained images in each split and class.
    dist = pd.crosstab(
        split_data["split"],
        split_data["label"],
    )
    dist = dist.reindex(
        index=list(RATIOS),
        columns=CLASSES,
        fill_value=0,
    )

    # Each split must contain examples of both classes.
    if (dist == 0).any().any():
        raise RuntimeError("A split is missing a class.")

    # Calculate actual split sizes and pneumonia percentages.
    dist["total"] = dist[CLASSES].sum(axis=1)
    dist["dataset_pct"] = (
        100 * dist["total"] / len(split_data)
    ).round(2)
    dist["pneumonia_pct"] = (
        100 * dist["PNEUMONIA"] / dist["total"]
    ).round(2)

    # ---------------------------------------------------------------
    # 6. Save split assignments and the summary.
    # ---------------------------------------------------------------

    OUT.mkdir(parents=True, exist_ok=True)

    # Record excluded duplicate copies.
    # The original files remain in their existing folders.
    removed.to_csv(
        OUT / "removed_duplicates.csv",
        index=False,
    )

    # Save one CSV image list for each new split.
    for split in RATIOS:
        subset = split_data[split_data["split"] == split]
        subset.to_csv(
            OUT / f"{split}.csv",
            index=False,
        )

    # Save the actual class distribution for the new assignments.
    dist.to_csv(OUT / "split_distribution.csv")

    # Record settings, results, and limitations for the project report.
    summary = (
        f"Random seed: {SEED}\n"
        f"Input images: {len(df)}\n"
        f"Redundant identical-file copies excluded: {len(removed)}\n"
        f"Retained images: {len(split_data)}\n"
        f"Connected groups: {split_data['group_id'].nunique()}\n"
        f"Target proportions: {RATIOS}\n\n"
        f"{dist.to_string()}\n\n"
        "Grouping uses filename-derived candidate IDs and file hashes.\n"
        "Actual patient identity and independence are unverified.\n"
        "Whole-group allocation produces approximate split proportions.\n"
        "The supplied splits have been replaced by custom assignments.\n"
        "Original image files were not changed or deleted.\n"
    )

    (OUT / "split_summary.txt").write_text(
        summary,
        encoding="utf-8",
    )

    print(summary)
    print(f"Saved split files to: {OUT}")


# Start the splitting process when this file is run directly.
if __name__ == "__main__":
    main()